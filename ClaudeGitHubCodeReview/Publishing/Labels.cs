using ClaudeGitHubCodeReview.Review;

namespace ClaudeGitHubCodeReview.Publishing;

/// <summary>
/// The fixed texts the tool itself adds around the model's findings. The model already writes in the
/// review language; these labels follow it so a Bosnian review does not have English headings.
/// Add a new language by adding another instance and a case in <see cref="For"/>.
/// </summary>
public sealed record Labels(
    string ReviewTitle,
    string FocusLine,
    string SkillsLine,
    string Domain,
    string Summary,
    string Strengths,
    string Findings,
    string NotInline,
    string Suggestion,
    string Severity,
    string Category,
    string Location,
    string GeneratedBy,
    string SnapshotPrTitle,
    string SnapshotPrBody,
    IReadOnlyDictionary<string, string> SeverityNames,
    IReadOnlyDictionary<string, string> CategoryNames)
{
    public static Labels For(string language) =>
        language.Equals(LanguageDetector.Bosnian, StringComparison.OrdinalIgnoreCase)
        || language.StartsWith("bs", StringComparison.OrdinalIgnoreCase)
            ? Bosnian
            : English;

    /// <summary>The skills the review used; reports from before skills existed fall back to the old focus line.</summary>
    public string Focus(ReviewMeta? meta) =>
        meta?.Skills is { Count: > 0 } skills ? string.Format(SkillsLine, string.Join(", ", skills)) : FocusLine;

    public string SeverityName(string severity) => SeverityNames.TryGetValue(severity, out var n) ? n : severity;

    public string CategoryName(string category) => CategoryNames.TryGetValue(category, out var n) ? n : category;

    public static readonly Labels English = new(
        ReviewTitle: "Automated code review",
        FocusLine: "Focus: authentication & authorization, DDD, Clean Architecture, EF Core queries (backend).",
        SkillsLine: "Skills used: {0}.",
        Domain: "Domain as understood by the reviewer",
        Summary: "Summary",
        Strengths: "What is already good",
        Findings: "Findings",
        NotInline: "Findings that could not be attached to a diff line",
        Suggestion: "Suggestion",
        Severity: "Severity",
        Category: "Category",
        Location: "Location",
        GeneratedBy: "Generated by ClaudeGitHubCodeReview with Claude Code, run by",
        SnapshotPrTitle: "Code review: full snapshot of {0}@{1} (do not merge)",
        SnapshotPrBody: """
            This draft pull request exists only to hold a **review of the existing codebase**.

            * `{0}` contains an empty tree, `{1}` contains `{2}` at commit `{3}`, so every file appears as "added" and every line can carry a review comment.
            * **Do not merge.** Close the PR and delete both `code-review/...` branches when the review has been discussed.
            """,
        SeverityNames: new Dictionary<string, string> { ["critical"] = "Critical", ["high"] = "High", ["medium"] = "Medium", ["low"] = "Low" },
        CategoryNames: new Dictionary<string, string>
        {
            ["authentication"] = "Authentication", ["authorization"] = "Authorization", ["ddd"] = "DDD",
            ["clean-architecture"] = "Clean Architecture", ["ef-core"] = "EF Core", ["security"] = "Security",
            ["correctness"] = "Correctness", ["other"] = "Other",
        });

    public static readonly Labels Bosnian = new(
        ReviewTitle: "Automatski code review",
        FocusLine: "Fokus: autentifikacija i autorizacija, DDD, Clean Architecture, EF Core upiti (backend).",
        SkillsLine: "Korišteni skillovi: {0}.",
        Domain: "Domen kako ga je reviewer razumio",
        Summary: "Sažetak",
        Strengths: "Šta je već dobro urađeno",
        Findings: "Nalazi",
        NotInline: "Nalazi koji nisu mogli biti vezani za liniju u diffu",
        Suggestion: "Prijedlog",
        Severity: "Ozbiljnost",
        Category: "Kategorija",
        Location: "Lokacija",
        GeneratedBy: "Generisao ClaudeGitHubCodeReview uz Claude Code, pokrenuo",
        SnapshotPrTitle: "Code review: kompletan snimak {0}@{1} (ne mergeati)",
        SnapshotPrBody: """
            Ovaj draft pull request postoji samo da bi nosio **review postojećeg koda**.

            * `{0}` sadrži prazno stablo, a `{1}` sadrži `{2}` na commitu `{3}`, pa se svaki fajl vidi kao "dodan" i svaka linija može dobiti komentar.
            * **Ne mergeati.** Kada se review prođe, zatvoriti PR i obrisati obje `code-review/...` grane.
            """,
        SeverityNames: new Dictionary<string, string> { ["critical"] = "Kritično", ["high"] = "Visoko", ["medium"] = "Srednje", ["low"] = "Nisko" },
        CategoryNames: new Dictionary<string, string>
        {
            ["authentication"] = "Autentifikacija", ["authorization"] = "Autorizacija", ["ddd"] = "DDD",
            ["clean-architecture"] = "Clean Architecture", ["ef-core"] = "EF Core", ["security"] = "Sigurnost",
            ["correctness"] = "Ispravnost", ["other"] = "Ostalo",
        });
}
